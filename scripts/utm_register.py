#!/usr/bin/env python3
"""UTM register: every utm_source / utm_medium / utm_campaign seen on website form leads (HubSpot) and website
visits (Leadfeeder), so new UTMs are tracked and checked against the GTM campaign tracker.

Arushi, 18 Nov 2026: "New UTMs should be properly tracked." Jolanta, 17 Nov: every page/campaign UTM goes in the
campaign tracker (inploi_GTM_Campaign_Tracker, Drive 1-Wl2diLpSZL9cCJzS03-POzdMN2C4ZNyhtXrazGw0b4) so we can see
which UTM brought how many visitors.

Usage (end-of-day scheduled task, or by hand):
  1. curl "https://inploi-sdr-portal.vercel.app/api/data?part=forms&days=120&v=<ts>" > <folder>/forms.json
  2. Optional: export the tracker's Campaigns tab utm_campaign values, one per line, to <folder>/tracker.txt
  3. python3 -I scripts/utm_register.py <folder> [YYYY-MM-DD today]
Writes api/_utms.json (state) and docs/utm-register.md (readable table), and prints the UTMs first seen today.

Keeps IDs and UTM values only: no names or emails.
"""
import json, os, sys, datetime

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
STATE, DOC, VISITS = (os.path.join(ROOT, p) for p in ('api/_utms.json', 'docs/utm-register.md', 'api/_visits.json'))
NOT_UTM_MEDIUM = {'', 'organic', 'referral', '(none)', 'none'}


def norm(x):
    return str(x or '').strip().lower()


def main(folder, today):
    try:
        state = json.load(open(STATE))
    except Exception:
        state = {'utms': {}}
    U = state['utms']
    load = lambda f: json.load(open(os.path.join(folder, f))) if os.path.exists(os.path.join(folder, f)) else None
    tracker = set()
    if os.path.exists(os.path.join(folder, 'tracker.txt')):
        tracker = {norm(l) for l in open(os.path.join(folder, 'tracker.txt')) if norm(l)}

    seen = {}  # key -> {'forms': set(ids), 'visits': set(ids), 'first': date}

    def add(src, med, cmp, kind, rid, day):
        k = ' / '.join([norm(src) or '(no source)', norm(med) or '(no medium)', norm(cmp) or '(no campaign)'])
        s = seen.setdefault(k, {'forms': set(), 'visits': set(), 'first': day, 'last': day})
        s[kind].add(str(rid))
        s['first'], s['last'] = min(s['first'], day), max(s['last'], day)

    forms = load('forms.json') or {}
    for r in forms.get('external', []):
        t = r.get('traffic') or {}
        day = datetime.datetime.fromtimestamp((r.get("at") or 0) / 1000, datetime.timezone.utc).strftime('%Y-%m-%d')
        if t.get('utm_source') or t.get('utm_medium') or t.get('utm_campaign'):
            add(t.get('utm_source'), t.get('utm_medium'), t.get('utm_campaign'), 'forms', r.get('id'), day)
        elif t.get('source') == 'OTHER_CAMPAIGNS' and t.get('d1'):
            # HubSpot stores the UTM campaign of a tagged link as Original Source "Other campaigns" + drill-down 1
            add('hubspot', 'other campaigns', t.get('d1'), 'forms', r.get('id'), day)
    try:
        vis = json.load(open(VISITS)).get('visits', [])
    except Exception:
        vis = []
    for v in vis:
        if norm(v.get('med')) in NOT_UTM_MEDIUM and not v.get('cmp'):
            continue
        add(v.get('src'), v.get('med'), v.get('cmp'), 'visits', v.get('id'), (v.get('t') or '')[:10])

    new = []
    for k, s in seen.items():
        old = U.get(k)
        if not old:
            new.append(k)
            U[k] = {'firstSeen': s['first'], 'loggedOn': today}
        u = U[k]
        u['firstSeen'] = min(u['firstSeen'], s['first'])
        u['lastSeen'] = max(u.get('lastSeen', ''), s['last'])
        u['formIds'] = sorted(set(u.get('formIds', [])) | s['forms'])
        u['visits'] = max(u.get('visits', 0), len(s['visits']))  # visits age out of the 120-day snapshot: keep the high-water mark
        cmp = k.split(' / ')[2]
        u['inTracker'] = (cmp in tracker) if tracker else u.get('inTracker')
    state['updatedAt'] = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    json.dump(state, open(STATE, 'w'), indent=1, sort_keys=True)

    rows = sorted(U.items(), key=lambda kv: kv[1].get('lastSeen', ''), reverse=True)
    yn = lambda x: 'yes' if x is True else 'NO' if x is False else '?'
    lines = ['# UTM register', '',
             'Every utm_source / utm_medium / utm_campaign seen on website form leads (HubSpot) and website visits (Leadfeeder).',
             'Generated by `scripts/utm_register.py` at the end of each day; do not edit by hand. "In tracker" = the campaign is',
             'listed in inploi_GTM_Campaign_Tracker (Campaigns tab). Anything marked NO should be added to the tracker.', '',
             '| Source / medium / campaign | First seen | Last seen | Form leads | Visits | In tracker |',
             '|---|---|---|---|---|---|']
    for k, u in rows:
        lines.append('| %s | %s | %s | %d | %d | %s |' % (k, u['firstSeen'], u.get('lastSeen', ''), len(u.get('formIds', [])), u.get('visits', 0), yn(u.get('inTracker'))))
    open(DOC, 'w').write('\n'.join(lines) + '\n')
    print(json.dumps({'utms': len(U), 'newToday': new, 'notInTracker': [k for k, u in U.items() if u.get('inTracker') is False]}))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else datetime.date.today().isoformat())
